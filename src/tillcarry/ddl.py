"""PostgreSQL DDL text built from a Plan. Constraints and indexes are separate statements so the migrator can
load data first and add them afterwards."""

from __future__ import annotations

import hashlib

from .introspect import ForeignKey, Index
from .plan import TablePlan


def qi(name: str) -> str:
    """Quote an identifier."""
    return '"' + name.replace('"', '""') + '"'


def pg_name(table: str, name: str) -> str:
    """Constraint and index names are schema wide in PostgreSQL, so they carry the table name. Max 63 bytes."""
    full = name if name.startswith(table) else f"{table}_{name}"
    if len(full) <= 63:
        return full
    return full[:54] + "_" + hashlib.sha1(full.encode()).hexdigest()[:8]


def create_table(schema: str, t: TablePlan) -> str:
    lines = []
    for c in t.columns:
        parts = [qi(c.name), c.pg.sql]
        if c.col.name == t.identity:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if not c.col.nullable:
            parts.append("NOT NULL")
        if c.default_sql is not None and c.col.name != t.identity:
            parts.append(f"DEFAULT {c.default_sql}")
        lines.append("  " + " ".join(parts))
    return f"CREATE TABLE {qi(schema)}.{qi(t.name)} (\n" + ",\n".join(lines) + "\n)"


def add_primary_key(schema: str, t: TablePlan) -> str | None:
    if not t.pk:
        return None
    cols = ", ".join(qi(c) for c in t.pk)
    return f"ALTER TABLE {qi(schema)}.{qi(t.name)} ADD CONSTRAINT {qi(pg_name(t.name, 'pkey'))} PRIMARY KEY ({cols})"


def add_unique(schema: str, t: TablePlan, idx: Index) -> str:
    cols = ", ".join(qi(c) for c in idx.columns)
    return f"ALTER TABLE {qi(schema)}.{qi(t.name)} ADD CONSTRAINT {qi(pg_name(t.name, idx.name))} UNIQUE ({cols})"


def create_index(schema: str, t: TablePlan, idx: Index) -> str:
    cols = ", ".join(qi(c) for c in idx.columns)
    return f"CREATE INDEX {qi(pg_name(t.name, idx.name))} ON {qi(schema)}.{qi(t.name)} ({cols})"


_RULES = {"NO ACTION": "NO ACTION", "RESTRICT": "RESTRICT", "CASCADE": "CASCADE", "SET NULL": "SET NULL"}


def add_foreign_key(schema: str, fk: ForeignKey) -> str:
    cols = ", ".join(qi(c) for c in fk.columns)
    rcols = ", ".join(qi(c) for c in fk.ref_columns)
    rule = _RULES.get(fk.on_delete.upper(), "NO ACTION")
    return (
        f"ALTER TABLE {qi(schema)}.{qi(fk.table)} ADD CONSTRAINT {qi(pg_name(fk.table, fk.name))} "
        f"FOREIGN KEY ({cols}) REFERENCES {qi(schema)}.{qi(fk.ref_table)} ({rcols}) ON DELETE {rule}"
    )
